CREATE TABLE IF NOT EXISTS brands (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  contact_name VARCHAR(200),
  contact_number VARCHAR(40),
  email VARCHAR(320),
  industry VARCHAR(120),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS collaborations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id BIGINT NOT NULL REFERENCES brands(id) ON DELETE RESTRICT,
  campaign_name VARCHAR(200) NOT NULL,
  deal_amount NUMERIC(12, 2) CHECK (deal_amount IS NULL OR deal_amount >= 0),
  start_date DATE,
  end_date DATE,
  status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS idx_collaborations_brand_id ON collaborations(brand_id);

CREATE TABLE IF NOT EXISTS usage_rights (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  collaboration_id BIGINT NOT NULL REFERENCES collaborations(id) ON DELETE CASCADE,
  content_title VARCHAR(250) NOT NULL,
  platform VARCHAR(120) NOT NULL,
  usage_type VARCHAR(20) NOT NULL CHECK (usage_type IN ('ORGANIC','PAID_AD','LICENSING','WHITELISTING')),
  start_date DATE,
  expiry_date DATE,
  renewal_fee NUMERIC(12, 2) CHECK (renewal_fee IS NULL OR renewal_fee >= 0),
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (start_date IS NULL OR expiry_date IS NULL OR expiry_date >= start_date)
);
CREATE INDEX IF NOT EXISTS idx_usage_rights_collaboration_id ON usage_rights(collaboration_id);
CREATE INDEX IF NOT EXISTS idx_usage_rights_expiry_date ON usage_rights(expiry_date);

CREATE TABLE IF NOT EXISTS exclusivity_periods (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  collaboration_id BIGINT NOT NULL REFERENCES collaborations(id) ON DELETE CASCADE,
  category VARCHAR(160) NOT NULL,
  start_date DATE,
  end_date DATE,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS idx_exclusivity_collaboration_id ON exclusivity_periods(collaboration_id);
